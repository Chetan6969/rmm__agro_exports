/**
 * Talking to each user's own mailbox: SMTP (nodemailer) to send, IMAP (imapflow) to read replies.
 * Everything goes through a MailDriver so tests can swap in an in-memory mailbox.
 */
import { MAIL_PROVIDERS } from '@rmm/shared';
import { ImapFlow } from 'imapflow';
import nodemailer from 'nodemailer';
import { AppError } from '../../core/errors.js';

export interface MailCredentials {
  email: string;
  displayName: string | null;
  provider: string;
  smtpHost: string;
  smtpPort: number;
  smtpSecure: boolean;
  imapHost: string;
  imapPort: number;
  imapSecure: boolean;
  username: string;
  password: string;
}

export interface OutgoingMail {
  to: { name: string | null; address: string };
  subject: string;
  text: string;
  /** Generated by us (so it is known before sending), with angle brackets. */
  messageId: string;
  inReplyTo?: string | null;
  references?: string[];
}

export interface FetchState {
  uidValidity: string | null;
  lastUid: number;
}

export interface FetchedBatch {
  uidValidity: string;
  lastUid: number;
  messages: { uid: number; source: Buffer }[];
}

export interface MailDriver {
  verify(c: MailCredentials): Promise<void>;
  send(c: MailCredentials, m: OutgoingMail): Promise<void>;
  /** New INBOX messages since `state` (or of the last `lookbackDays` days on first run / after a mailbox reset). */
  fetchNew(c: MailCredentials, state: FetchState, lookbackDays: number): Promise<FetchedBatch>;
}

const TIMEOUT = 20_000;
/** At most this many messages per check, so one huge inbox cannot stall the server. */
const BATCH = 200;

function smtp(c: MailCredentials) {
  return nodemailer.createTransport({
    host: c.smtpHost,
    port: c.smtpPort,
    secure: c.smtpSecure,
    requireTLS: !c.smtpSecure,
    auth: { user: c.username, pass: c.password },
    connectionTimeout: TIMEOUT,
    greetingTimeout: TIMEOUT,
    socketTimeout: TIMEOUT * 2,
  });
}

function imap(c: MailCredentials) {
  return new ImapFlow({
    host: c.imapHost,
    port: c.imapPort,
    secure: c.imapSecure,
    auth: { user: c.username, pass: c.password },
    logger: false,
    connectionTimeout: TIMEOUT,
    greetingTimeout: TIMEOUT,
    socketTimeout: TIMEOUT * 3,
  });
}

export const realDriver: MailDriver = {
  async verify(c) {
    const t = smtp(c);
    try {
      await t.verify();
    } catch (e) {
      throw explain(e, c, 'SMTP');
    } finally {
      t.close();
    }
    const client = imap(c);
    try {
      await client.connect();
      await client.logout();
    } catch (e) {
      client.close();
      throw explain(e, c, 'IMAP');
    }
  },

  async send(c, m) {
    const t = smtp(c);
    try {
      await t.sendMail({
        from: { name: c.displayName ?? c.email, address: c.email },
        to: m.to.name ? { name: m.to.name, address: m.to.address } : m.to.address,
        subject: m.subject,
        text: m.text,
        messageId: m.messageId,
        inReplyTo: m.inReplyTo ?? undefined,
        references: m.references?.length ? m.references : undefined,
      });
    } catch (e) {
      throw explain(e, c, 'SMTP');
    } finally {
      t.close();
    }
  },

  async fetchNew(c, state, lookbackDays) {
    const client = imap(c);
    try {
      await client.connect();
    } catch (e) {
      client.close();
      throw explain(e, c, 'IMAP');
    }
    try {
      const lock = await client.getMailboxLock('INBOX', { readOnly: true });
      try {
        const box = client.mailbox;
        const uidValidity = box ? String(box.uidValidity) : '';
        const fresh = !state.uidValidity || state.uidValidity !== uidValidity;
        const found = fresh
          ? await client.search({ since: new Date(Date.now() - lookbackDays * 86_400_000) }, { uid: true })
          : await client.search({ uid: `${state.lastUid + 1}:*` }, { uid: true });
        // "N:*" always returns the newest message even when nothing is newer than N
        const uids = (found || []).filter((u) => fresh || u > state.lastUid).sort((a, b) => a - b).slice(0, BATCH);
        const messages: { uid: number; source: Buffer }[] = [];
        if (uids.length) {
          for await (const msg of client.fetch(uids, { uid: true, source: true }, { uid: true })) {
            if (msg.source) messages.push({ uid: msg.uid, source: msg.source });
          }
        }
        const lastUid = uids.length ? uids[uids.length - 1] : fresh ? Math.max(0, Number(box && 'uidNext' in box ? box.uidNext : 1) - 1) : state.lastUid;
        return { uidValidity, lastUid, messages };
      } finally {
        lock.release();
      }
    } finally {
      await client.logout().catch(() => client.close());
    }
  },
};

let driver: MailDriver = realDriver;
export const mailDriver = () => driver;
/** Tests only: route all mail through an in-memory driver. */
export function setMailDriver(d: MailDriver | null) {
  driver = d ?? realDriver;
}

/** Turn library errors into a message and a hint the user can act on. */
export function explain(e: unknown, c: Pick<MailCredentials, 'provider' | 'email'>, side: 'SMTP' | 'IMAP'): AppError {
  if (e instanceof AppError) return e;
  const err = e as { code?: string; responseCode?: number; authenticationFailed?: boolean; message?: string; response?: string };
  const help = MAIL_PROVIDERS.find((p) => p.provider === c.provider)?.passwordHelp;
  const text = `${err.message ?? ''} ${err.response ?? ''}`;
  if (err.code === 'EAUTH' || err.authenticationFailed || err.responseCode === 535 || /auth|credential|password|login/i.test(text)) {
    return new AppError(400, 'mail_auth_failed', `The mail server did not accept the email address and app password (${side})`, help ?? 'Use an app password made for this ERP, not your normal sign-in password, and check that IMAP access is turned on for the mailbox.');
  }
  if (['ENOTFOUND', 'EDNS', 'EAI_AGAIN'].includes(err.code ?? '')) {
    return new AppError(400, 'mail_host_not_found', `The ${side} server name could not be found`, 'Check that the right provider (Google, Microsoft or Yahoo) is chosen, and that the ERP server can reach the internet.');
  }
  if (['ETIMEDOUT', 'ECONNREFUSED', 'ECONNRESET', 'ESOCKET', 'ECONNECTION'].includes(err.code ?? '') || /timeout|timed out/i.test(text)) {
    return new AppError(502, 'mail_unreachable', `Could not connect to the ${side} server`, 'Check that the office firewall allows the ERP server outgoing mail connections (ports 465/587 and 993), then try again.');
  }
  return new AppError(502, 'mail_failed', `The ${side} server refused the request: ${(err.message ?? 'unknown error').slice(0, 200)}`, 'Try again in a minute. If it keeps failing, check that the right provider is chosen in My mailbox.');
}
